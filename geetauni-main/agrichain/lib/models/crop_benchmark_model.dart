  /// Find benchmark by crop name (matches partial or full name)
  static CropBenchmark? findByName(String name) {
    final search = name.trim().toLowerCase();
    for (final crop in catalog) {
      if (crop.name.toLowerCase() == search ||
          crop.hindiName.toLowerCase() == search ||
          search.contains(crop.name.toLowerCase()) ||
          crop.name.toLowerCase().contains(search)) {
        return crop;
      }
    }
    // Fallback search by key terms
    if (search.contains('wheat') || search.contains('gehu') || search.contains('गेहूं')) {
      return catalog.firstWhere((c) => c.id == 'wheat_sharbati');
    }
    if (search.contains('rice') || search.contains('paddy') || search.contains('dhan') || search.contains('धान')) {
      return catalog.firstWhere((c) => c.id == 'rice_basmati');
    }
    if (search.contains('onion') || search.contains('pyaz') || search.contains('प्याज')) {
      return catalog.firstWhere((c) => c.id == 'veg_red_onion');
    }
    if (search.contains('potato') || search.contains('aloo') || search.contains('आलू')) {
      return catalog.firstWhere((c) => c.id == 'veg_table_potato');
    }
    if (search.contains('chana') || search.contains('चना')) {
      return catalog.firstWhere((c) => c.id == 'pulse_desi_chana');
    }
    if (search.contains('mustard') || search.contains('sarson') || search.contains('सरसों')) {
      return catalog.firstWhere((c) => c.id == 'oilseed_mustard');
    }
    if (search.contains('soy') || search.contains('सोया')) {
      return catalog.firstWhere((c) => c.id == 'oilseed_soybean');
    }
    if (search.contains('tomato') || search.contains('tamatar') || search.contains('टमाटर')) {
      return catalog.firstWhere((c) => c.id == 'veg_tomato');
    }
    return null;
  }

